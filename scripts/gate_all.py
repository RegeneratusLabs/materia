#!/usr/bin/env python3
"""One command, one report.

Aggregates the corpus state, coverage, panel conditions and gate results into
docs/gate_report.md plus a run manifest. Model runs are NOT repeated here: it reads the
artifacts that already exist, so the report always describes files on disk.
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from materia import config, manifest  # noqa: E402
from materia.corpus.index import stats as index_stats  # noqa: E402
from materia.corpus.schema import load_docs, validate_corpus  # noqa: E402


def read_json(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None


def main() -> int:
    results = config.RESULTS_DIR
    docs = load_docs(config.CORPUS_DIR / "docs")
    errors = validate_corpus(docs)
    idx = index_stats(config.CORPUS_DIR / "index.sqlite") if (config.CORPUS_DIR / "index.sqlite").exists() else {}
    coverage = read_json(config.DATA_DIR / "panel_coverage.json") or []
    audit = read_json(config.DATA_DIR / "panel_coverage_audit.json") or {}
    gate3 = read_json(results / "gate3_hybrid.json") or {}
    gate4 = read_json(results / "gate4.json") or {}
    abst = read_json(results / "gate3_abstention.json") or {}
    gate0 = read_json(results / "gate0_clean.json") or {}

    covered = sum(1 for r in coverage if r.get("covered"))
    lines = [
        f"# materia — gate report ({date.today().isoformat()})",
        "",
        "Generated by `scripts/gate_all.py` from artifacts on disk. No number here was typed by hand.",
        "",
        "## Corpus",
        "",
        f"- documents: **{len(docs)}**, chunks: **{idx.get('chunks', '?')}**, "
        f"redistributable: **{sum(1 for d in docs if (d.get('licence') or {}).get('redistributable'))}**",
        f"- schema errors: **{len(errors)}**",
        f"- by jurisdiction: {idx.get('by_jurisdiction', {})}",
        f"- by tier: {idx.get('by_tier', {})}",
        "",
        "## Panel coverage",
        "",
        f"- covered: **{covered}/{len(coverage)} = {100 * covered / max(1, len(coverage)):.1f}%**",
        f"- audit of covered items: {audit.get('counts', {})} "
        f"(precision of 'covered' as support: roughly 50%)",
        "",
        "## Conditions (all on the 104-item panel unless stated)",
        "",
        "| Condition | n | Result |",
        "|---|---|---|",
    ]
    for f in sorted(results.glob("*.summary.json")):
        s = read_json(f) or {}
        if "pct" not in s:
            continue
        label = s.get("condition", f.stem)
        if "max_tokens" in s:
            label = f"{label} (max_tokens {s['max_tokens']})"
        lines.append(f"| `{f.stem}` — {label} | {s.get('n')} | {s.get('correct')}/{s.get('n')} "
                     f"= {s.get('pct')}% {s.get('ci95', '')} |")
    if gate3:
        p = gate3.get("paired", {})
        lines += [
            "",
            "## Gate 3 — lab-only retrieval (paired)",
            "",
            f"- baseline {gate3.get('baseline', {}).get('score')} -> retrieval "
            f"{gate3.get('retrieval', {}).get('score')}",
            f"- fixed {p.get('fixed')}, broke {p.get('broke')}, McNemar p={p.get('mcnemar_exact_p')}",
            f"- citations in context: {gate3.get('traceability', {}).get('citations_in_context')}"
            f"/{gate3.get('traceability', {}).get('citations_total')}",
        ]
    if abst:
        lines += ["", "## Gate 3 — abstention", "", f"- {abst.get('abstained')}/{abst.get('n')} NO_EVIDENCE"]
    if gate0:
        lines += [
            "",
            "## Gate 0 — OCR",
            "",
            f"- values {gate0.get('value_accuracy_str')}, ref intervals {gate0.get('ref_accuracy_str')}, "
            f"silent wrong: {gate0.get('silent_wrong')}",
        ]
    if gate4:
        s = gate4.get("summary", {})
        lines += [
            "",
            "## Gate 4 — symptom workflow",
            "",
            f"- red flags {s.get('red_flag_matched')}/{s.get('red_flag_cases')}, "
            f"emergencies stopped {s.get('emergency_stopped')}/{s.get('emergency_cases')}, "
            f"vetoes {s.get('veto_ok')}/{s.get('veto_cases')}",
            f"- sheets contract-clean: {s.get('contract_clean')}/{s.get('generated')} "
            f"({s.get('contract_violations')} violations)",
        ]
    lines += [
        "",
        "## What is not 100%",
        "",
        "- clinical correctness is never claimed; the guarantees are provenance, refusal and the code rules",
        "- referral branch is thin (3/8 covered via MedlinePlus symptom pages; NICE CKS is geo-blocked)",
        "- lab branch is partial (19/30 covered via MedlinePlus test pages; no numeric intervals for every analyte)",
        "- herb retrieval is not shipped: the closed-book prior beats the corpus on herb questions",
        "- 48 panel items name no entity, so entity coverage cannot apply to them (closed-book 73/73)",
        "- run-to-run noise is ~1 item in 104 at -np 2; sub-2-item differences are undefined",
        "",
    ]
    out = config.ROOT / "docs" / "gate_report.md"
    out.write_text("\n".join(lines) + "\n")
    man = manifest.write(results / "gate_manifest.json")
    print(f"-> {out}")
    print(f"manifest: git {man['git_sha']}, corpus {man['corpus']['documents']} docs, "
          f"index {man['corpus']['index_bytes']} bytes")
    return 0 if not errors else 1


if __name__ == "__main__":
    raise SystemExit(main())
