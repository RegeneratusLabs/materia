#!/usr/bin/env python3
"""Generate the synthetic nutrient/lipid teaching panel used by the demo.

The image is not a patient record. It exists so the web app can show the full
assessment path (iron, B12, vitamin D, lipids) without a real report.
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

W, H = 1200, 1400
BG = "#f7f4ec"
INK = "#1f2f28"
MUTED = "#6d8076"
LINE = "#d8d2c4"
LOW = "#2f5f8a"
HIGH = "#8a3b2f"

ROWS = [
    ("Ferritin", "18", "µg/L", "15–150", "L"),
    ("Haemoglobin", "118", "g/L", "120–160", "L"),
    ("MCV", "84", "fL", "80–100", ""),
    ("Vitamin B12", "210", "pmol/L", "219–773", "L"),
    ("Methylmalonic acid", "320", "nmol/L", "0–270", "H"),
    ("25-hydroxyvitamin D", "45", "nmol/L", "75–250", "L"),
    ("ALT", "32", "U/L", "4–36", ""),
    ("Triglycerides", "1.9", "mmol/L", "0.4–1.7", "H"),
    ("LDL cholesterol", "3.4", "mmol/L", "0–2.6", "H"),
    ("HDL cholesterol", "1.1", "mmol/L", "1.0–3.0", ""),
    ("C-reactive protein", "3", "mg/L", "0–5", ""),
    ("TSH", "2.1", "mIU/L", "0.4–4.8", ""),
]

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
FONT_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


def main() -> int:
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)
    f_title = ImageFont.truetype(FONT_BOLD, 34)
    f_sub = ImageFont.truetype(FONT, 20)
    f_head = ImageFont.truetype(FONT_BOLD, 18)
    f_cell = ImageFont.truetype(FONT, 22)
    f_small = ImageFont.truetype(FONT, 17)

    d.text((70, 58), "materia · teaching panel", font=f_title, fill=INK)
    d.text((70, 108), "Synthetic nutrient & lipid panel — not a patient record", font=f_sub, fill=MUTED)
    d.text((70, 138), "Generated for local demonstration of the cited assessment path.", font=f_small, fill=MUTED)
    d.line((70, 190, W - 70, 190), fill=LINE, width=2)

    cols = [70, 540, 690, 820, 1030]
    headers = ["Analyte", "Result", "Unit", "Reference", "Flag"]
    for x, label in zip(cols, headers):
        d.text((x, 220), label, font=f_head, fill=MUTED)
    d.line((70, 250, W - 70, 250), fill=LINE, width=1)

    start_y = 300
    row_h = 72
    positions = {}
    for i, (name, value, unit, ref, flag) in enumerate(ROWS):
        y = start_y + i * row_h
        center = y + 36
        d.text((cols[0], center - 13), name, font=f_cell, fill=INK)
        d.text((cols[1], center - 13), value, font=f_cell, fill=INK)
        d.text((cols[2], center - 13), unit, font=f_cell, fill=MUTED)
        d.text((cols[3], center - 13), ref, font=f_cell, fill=MUTED)
        if flag:
            d.text((cols[4], center - 13), flag, font=f_head, fill=LOW if flag == "L" else HIGH)
        d.line((70, y + row_h - 1, W - 70, y + row_h - 1), fill=LINE, width=1)
        positions[name] = round(center / H * 100, 1)

    d.line((70, 1200, W - 70, 1200), fill=LINE, width=2)
    d.text((70, 1225), "Synthetic values. No patient data. Not for diagnosis or prescription.", font=f_small, fill=MUTED)
    d.text((70, 1255), "Reference intervals are illustrative; the lab's own interval wins in the app.", font=f_small, fill=MUTED)

    out = Path("materia/webapp/static/assets/sample-nutrient.png")
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out, optimize=True)
    payload = {
        "doc": "synthetic-nutrient-panel",
        "source_note": "Synthetic teaching panel generated by scripts/make_sample_nutrient.py; not a patient record.",
        "collected_at": "2026-11-01",
        "reported_at": "2026-11-02",
        "unit": "",
        "rows": [
            {
                "analyte": name,
                "value": float(value) if "." in value else int(value),
                "unit": unit,
                "ref_low": float(ref.split("–")[0]) if "." in ref.split("–")[0] else int(ref.split("–")[0]),
                "ref_high": float(ref.split("–")[1]) if "." in ref.split("–")[1] else int(ref.split("–")[1]),
                "flag": flag or None,
                "y": positions[name],
            }
            for name, value, unit, ref, flag in ROWS
        ],
    }
    (Path("materia/webapp/static/assets/sample-nutrient.json")).write_text(
        json.dumps(payload, indent=1) + "\n"
    )
    print(f"wrote {out} and sample-nutrient.json ({len(ROWS)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
